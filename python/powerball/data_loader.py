"""Load and manage Powerball historical data."""

import csv
from typing import List, Optional
from pathlib import Path


DATA_DIR = Path(__file__).resolve().parent.parent / "data"
DEFAULT_CSV = DATA_DIR / "powerball_history.csv"

DATE_COL = "date"
N1_COL = "number1"
N2_COL = "number2"
N3_COL = "number3"
N4_COL = "number4"
N5_COL = "number5"
PB_COL = "powerball"
MP_COL = "multiplier"

COLUMNS = [DATE_COL, N1_COL, N2_COL, N3_COL, N4_COL, N5_COL, PB_COL, MP_COL]


def get_data_path() -> Path:
    return DEFAULT_CSV


def ensure_data_dir():
    DATA_DIR.mkdir(parents=True, exist_ok=True)


def load_draws(csv_path: Optional[Path] = None) -> List[dict]:
    """Load all draws from CSV, sorted by date ascending."""
    path = csv_path or DEFAULT_CSV
    if not path.exists():
        print(f"[INFO] No data file found. Creating starter data...")
        create_starter_data(path)

    draws = []
    with open(path, "r", newline="") as f:
        for row in csv.DictReader(f):
            draws.append({
                DATE_COL: row[DATE_COL].strip(),
                N1_COL: int(row[N1_COL]),
                N2_COL: int(row[N2_COL]),
                N3_COL: int(row[N3_COL]),
                N4_COL: int(row[N4_COL]),
                N5_COL: int(row[N5_COL]),
                PB_COL: int(row[PB_COL]),
                MP_COL: int(row.get(MP_COL, "1") or "1"),
            })
    draws.sort(key=lambda d: d[DATE_COL])
    return draws


def add_draw(date: str, n1: int, n2: int, n3: int, n4: int, n5: int,
             powerball: int, multiplier: int = 1, csv_path: Optional[Path] = None):
    """Append a new draw to the CSV file."""
    path = csv_path or DEFAULT_CSV
    ensure_data_dir()
    exists = path.exists()
    with open(path, "a", newline="") as f:
        w = csv.writer(f)
        if not exists:
            w.writerow(COLUMNS)
        w.writerow([date, n1, n2, n3, n4, n5, powerball, multiplier])
    print(f"[INFO] Added draw on {date}: {n1} {n2} {n3} {n4} {n5} PB:{powerball}")


